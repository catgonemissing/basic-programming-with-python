# All arithmetic operators on x and y

x = 17
y = 5

print(x + y)    # Addition: 17 + 5 = 22
print(x - y)    # Subtraction: 17 - 5 = 12
print(x * y)    # Multiplication: 17 * 5 = 85
print(x / y)    # Division: 17 / 5 = 3.4 (always returns float)
print(x // y)   # Floor Division: 17 // 5 = 3 (rounds down, drops decimal)
print(x % y)    # Modulo: 17 % 5 = 2 (remainder of 17 ÷ 5)
print(x ** y)   # Power: 17 ** 5 = 1419857 (17 to the power of 5)